/**
 * @brief  Handle Hard Fault exceptions (with support for semihosting).
 *
 * This handler must be entirely assembly: returning with BX LR is part of
 * the exception-return protocol and a C prologue/epilogue would corrupt it.
 */
void HardFault_Handler(void) __attribute__((naked, used));
void HardFault_Handler(void)
{
    __asm volatile(
        ".syntax unified\n"
        "movs r0, #4\n"
        "mov r1, lr\n"
        "tst r1, r0\n"
        "beq 1f\n"
        "mrs r0, psp\n"
        "b 2f\n"
        "1:\n"
        "mrs r0, msp\n"
        "2:\n"
        "ldr r1, [r0, #24]\n"
        "ldrh r2, [r1]\n"
        "ldr r3, =0xBEAB\n"
        "cmp r2, r3\n"
        "bne 3f\n"
        "adds r1, #2\n"
        "str r1, [r0, #24]\n"
        "movs r1, #32\n"
        "str r1, [r0]\n"
        "bx lr\n"
        "3:\n"
        "b 3b\n");
}

